/** Claves planas: `grupo.clave` para los grupos y la clave tal cual si es plana. */
export type MessageKey = {
  [K in keyof typeof es]: (typeof es)[K] extends string
    ? K
    : `${K & string}.${keyof (typeof es)[K] & string}`;
}[keyof typeof es];

/** Misma forma que el diccionario castellano pero con valores `string`. */
export type Dictionary = {
  [K in keyof typeof es]: (typeof es)[K] extends string
    ? string
    : { [P in keyof (typeof es)[K]]: string };
};
